"""Write the simple case folding table the room and charter readers fold by, into each skill that reads it.

The room profile (schema-dist `profiles/room.md`) compares a type and a supertype "after simple case
folding: each code point replaced by its mapping in the C and S rows of Unicode's CaseFolding.txt at
version 15.1, the table the schema distribution carries at `fixtures/owworld/CaseFolding-15.1.0.txt`",
never a language's lower-casing and never full folding; the charter profile folds its pairs the same
way ("defined once in the room profile"). Python's `str.casefold()` is full folding, at the Unicode
version of whoever runs it, so the readers carry the table instead.

Each copy below is the same bytes: rows C and S of that file as runs of (start, count, stride, delta),
the source's sha256 in the head, and `simple_fold(text)`. A skill installs alone, so each skill that
reads a pair carries its own copy:

    skills/onlyworlds-draw/scripts/simple_fold.py    (graph.py, and map.py and timeline.py through it)
    skills/onlyworlds-read/scripts/simple_fold.py    (count.py)
    skills/onlyworlds-setup/scripts/simple_fold.py   (write_world.py's reading aids)

The source is the schema-dist checkout beside this repository's main checkout (found through git from a
worktree too), or the file OW_CASEFOLDING names. testing/test_room_pairs.py regenerates the text and
compares it with every copy.

Usage:
    python testing/gen_casefold.py [TOOLKIT_DIR]           write the three copies
    python testing/gen_casefold.py --check [TOOLKIT_DIR]   exit 1 if any copy differs

Python 3, stdlib only. The copies are written with LF endings.
"""
import hashlib
import os
import subprocess
import sys
from pathlib import Path

COPIES = ("skills/onlyworlds-draw/scripts/simple_fold.py",
          "skills/onlyworlds-read/scripts/simple_fold.py",
          "skills/onlyworlds-setup/scripts/simple_fold.py")
SOURCE_NAME = "fixtures/owworld/CaseFolding-15.1.0.txt"


def source_path(toolkit):
    """The CaseFolding file: OW_CASEFOLDING, else schema-dist's beside the toolkit's main checkout."""
    if os.environ.get("OW_CASEFOLDING"):
        return Path(os.environ["OW_CASEFOLDING"])
    roots = [toolkit]
    try:
        common = subprocess.run(["git", "-C", str(toolkit), "rev-parse", "--path-format=absolute",
                                 "--git-common-dir"], capture_output=True, text=True).stdout.strip()
        if common:
            roots.insert(0, Path(common).parent)
    except OSError:
        pass
    found = [r.parent / "schema-dist" / SOURCE_NAME for r in roots]
    return next((p for p in found if p.exists()), found[0])


def rows_of(data):
    """{code point: its fold} from the C and S rows."""
    rows = {}
    for line in data.decode("utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = (p.strip() for p in line.split(";")[:3])
        if status in ("C", "S"):
            rows[int(code, 16)] = int(mapping, 16)
    return rows


def runs_of(rows):
    """Runs of (start, count, stride, delta): start, start + stride, ... fold to themselves + delta."""
    runs, codes, i = [], sorted(rows), 0
    while i < len(codes):
        start, delta = codes[i], rows[codes[i]] - codes[i]
        count, stride = 1, 0
        if i + 1 < len(codes) and rows[codes[i + 1]] - codes[i + 1] == delta:
            stride = codes[i + 1] - start
            while (i + count < len(codes) and codes[i + count] == start + count * stride
                   and rows[codes[i + count]] - codes[i + count] == delta):
                count += 1
        runs.append((start, count, stride or 1, delta))
        i += count
    return runs


def text_of(data):
    rows = rows_of(data)
    runs = runs_of(rows)
    assert {s + k * st: s + k * st + d for s, n, st, d in runs for k in range(n)} == rows
    lines = [
        '"""Unicode 15.1 simple case folding: the C and S rows of CaseFolding.txt, as the room profile folds a',
        "type and a supertype (schema-dist profiles/room.md; the charter profile folds its pairs the same way).",
        "",
        "GENERATED by testing/gen_casefold.py from the schema distribution's",
        f"{SOURCE_NAME} (sha256 {hashlib.sha256(data).hexdigest()}).",
        "Do not edit by hand. Never str.casefold(): that is full folding, at the Unicode version of whoever runs it.",
        f"{len(rows)} rows, as runs of (start, count, stride, delta): code points start, start + stride, ...",
        "(count of them) fold to themselves plus delta; a code point in no run folds to itself.",
        '"""',
        "",
        f"ROWS = {len(rows)}",
        "",
        "FOLD_RUNS = (",
        *(f"    (0x{s:04X}, {n}, {st}, {d})," for s, n, st, d in runs),
        ")",
        "",
        "_TABLE = {}",
        "",
        "",
        "def simple_fold(text):",
        '    """The text, each code point replaced by its simple case folding."""',
        "    if not _TABLE:",
        "        _TABLE.update({s + k * st: s + k * st + d for s, n, st, d in FOLD_RUNS for k in range(n)})",
        "    return text.translate(_TABLE)",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    toolkit = Path(args[0]).resolve() if args else Path(__file__).resolve().parent.parent
    src = source_path(toolkit)
    if not src.exists():
        print(f"no {SOURCE_NAME} at {src}: clone schema-dist beside the toolkit, or set OW_CASEFOLDING")
        return 2
    text = text_of(src.read_bytes()).encode("utf-8")
    differ = []
    for rel in COPIES:
        p = toolkit / rel
        if check:
            if not p.exists() or p.read_bytes().replace(b"\r\n", b"\n") != text:  # a CRLF checkout is the same text
                differ.append(rel)
        else:
            p.write_bytes(text)
    if check:
        print(f"casefold: {len(COPIES)} copies, {len(differ)} differ from {src}" + (f": {', '.join(differ)}" if differ else ""))
        return 1 if differ else 0
    print(f"casefold: wrote {len(COPIES)} copies, {len(text)} bytes each, from {src}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
